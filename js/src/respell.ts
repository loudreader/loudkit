/**
 * Polish lexical respelling — a bit-parity port of
 * `loudkit.frontend.polish.lexical_respelling` (which is itself the Python half
 * of the Swift engine's `LexicalRespelling`).
 *
 * English words embedded in Polish text are respelled the way a Polish reader
 * says them: "download" → "dałnloud", "deadline'u" → "dedlajnu". Numbers
 * become Polish cardinals, acronyms are spelled with Polish letter names, code
 * tokens are spelled out, and inflected loanwords are matched by stem + known
 * Polish ending.
 *
 * Dictionary-first and ONLY dictionary: a rule-based English G2P would misfire
 * on real Polish words, and the cost of a false positive (mangling native
 * text) is far higher than the cost of a miss. The 110k CMUdict long tail is
 * generated by `tools/gen_pl_respell.py` and shipped as `pl_en_respell.json`
 * in this package.
 */

